def user_tables(engine: Engine) -> set[str]:
    return set(inspect(engine).get_table_names()) - {"alembic_version"}


def test_upgrade_downgrade_upgrade(alembic_cfg: Config, engine: Engine) -> None:
    assert len(user_tables(engine)) == EXPECTED_TABLES

    command.downgrade(alembic_cfg, "base")
    with engine.connect() as conn:
        assert user_tables(engine) == set()
        assert conn.scalar(text("SELECT count(*) FROM pg_type WHERE typtype = 'e'")) == 0
        assert conn.scalar(text("SELECT count(*) FROM pg_matviews")) == 0

    command.upgrade(alembic_cfg, "head")
    assert len(user_tables(engine)) == EXPECTED_TABLES


