def test_no_cv_content_columns(engine: Engine) -> None:
    # Karar #9: CV dosyası / ham CV metni hiçbir sütunda tutulmaz; sadece hash ve sayfa sayısı.
    cv_columns = {
        f"{table}.{col['name']}"
        for table in user_tables(engine)
        for col in inspect(engine).get_columns(table)
        if any(word in col["name"] for word in ("cv", "resume", "ozgecmis"))
    }
    assert cv_columns == {"analyses.cv_sha256", "analyses.cv_pages"}


def make_user_with_analysis(session: Session) -> User:
    role = Role(name="Backend Developer", slug="backend-developer")
    skill = Skill(canonical_name="PostgreSQL", slug="postgresql", category=SkillCategory.VERITABANI)
    user = User(email="Ornek@Example.com", password_hash="x", target_role=role)  # noqa: S106 — sahte test verisi
    session.add_all([role, skill, user])
    session.flush()
    analysis = Analysis(user=user, target_role=role, cv_sha256="a" * 64, status=AnalysisStatus.DONE)
    analysis.skills.append(AnalysisSkill(skill_id=skill.id, kind=SkillKind.MISSING, priority=1))
    session.add_all(
        [analysis, Consent(user=user, consent_type=ConsentType.ACIK_RIZA, version="2026-12", accepted_at=text("now()"))]
    )
    session.add(AuditLog(user_id=user.id, action="analysis.create"))
    session.flush()
    return user


def test_orm_defaults_and_enum_values(session: Session) -> None:
    user = make_user_with_analysis(session)
    session.refresh(user)

    assert isinstance(user.id, uuid.UUID)
    assert user.created_at.tzinfo is not None  # timestamptz
    assert user.is_verified is False
    # citext: farklı harf büyüklüğüyle aranınca da bulunur.
    assert session.scalar(select(User).where(User.email == "ornek@example.com")) is user
    # DB'ye Python adı (ACIK_RIZA) değil değer (acik_riza) yazılır.
    assert session.scalar(text("SELECT consent_type::text FROM consents")) == "acik_riza"
    assert session.scalar(text("SELECT level::text FROM analysis_skills")) == SkillLevel.UNKNOWN.value


def test_hard_delete_user_cascades_personal_data(session: Session) -> None:
    user = make_user_with_analysis(session)
    session.delete(user)
    session.flush()

    for table in ("analyses", "analysis_skills", "consents"):
        assert session.scalar(text(f"SELECT count(*) FROM {table}")) == 0, table  # noqa: S608 — sabit tablo adları
    # Denetim kaydı kalır, kişi bağı kopar.
    assert session.scalar(text("SELECT count(*) FROM audit_logs WHERE user_id IS NULL")) == 1


